import {build} from 'esbuild';
import {readFile,writeFile,mkdir,rm} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const bundle=await build({entryPoints:[path.join(root,'Browser/game.mjs')],bundle:true,write:false,format:'iife',minify:true,target:['es2020'],legalComments:'inline'});
let html=await readFile(path.join(root,'Browser/index.html'),'utf8');
const css=await readFile(path.join(root,'Browser/style.css'),'utf8');
const license=await readFile(path.join(root,'node_modules/three/LICENSE'),'utf8');
html=html.replace('<link rel="stylesheet" href="style.css">',()=>`<style>${css}</style>`);
html=html.replace('<script type="module" src="game.mjs"></script>',()=>`<!-- Three.js license:\n${license.replaceAll('--','—')}\n-->\n<script>${bundle.outputFiles[0].text.replaceAll('</script','<\\/script')}</script>`);
html=html.replace('href="./"','href="#"');
html=html.replace(/[ \t]+$/gm,'');
await writeFile(path.join(root,'Browser/Play-Pitfall.html'),html);
await rm(path.join(root,'_site'),{recursive:true,force:true});
await mkdir(path.join(root,'_site'),{recursive:true});
await writeFile(path.join(root,'_site/index.html'),html);
await writeFile(path.join(root,'_site/.nojekyll'),'');
console.log('Built standalone 3D game and GitHub Pages site.');
